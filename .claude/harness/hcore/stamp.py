# Profile stamp: the `profiles` key of .claude/harness.json.
#
# - HJ-01: only the `profiles` key is written (ordered list of
#   {name, added, by}); every other key, `autonomy` included, is kept as is.
#   Atomic write, strict JSON, indent 2, keys in their original order.
# - HJ-02: unreadable JSON, or `profiles` that is not a list: error, file not
#   rewritten.
# - HJ-03: the core only ADDS. There is no removal. A profile already present
#   is not duplicated and keeps its `added`; a write without addition leaves
#   the file untouched (byte for byte).
# - HJ-04: `resolve`: stamp, else inferred from the files generated by a
#   pre-Phase 2 installation, else none.
# - HJ-05: the skill writes the stamp last (nothing here writes it earlier).
# - EP-03: `compare` of the stamp with a scout verdict: added / kept / vanished
#   (vanished is reported, never removed).
#
# Phase 3 (schema_version 1, documented in STAMP.md):
# - HJ-07, HJ-10, HJ-13: `compose` builds the complete stamp (autonomy, profiles,
#   skills.<skill>, migrations[], inferred_from) from an existing one.
# - HJ-08: every existing key is kept, unknown ones included, in their order; new
#   keys come after. HJ-09: `autonomy` absent -> "auto", an existing value is never modified.
# - HJ-12: `validate_data` refuses absolute paths and `rg_path` (the stamp is versioned).
# - HJ-15: `show`, `validate_file`. DT-01, DT-02: `resolve_full`.

from __future__ import annotations

import json
import os
import re
import tempfile
from datetime import date, datetime
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

from . import profiles

STAMP_FILE = Path(".claude") / "harness.json"
BY_VALUES = ("scout", "forced", "inferred", "fallback")


class StampError(ValueError):
    """Unreadable stamp or invalid request (exit 2)."""


def _read(root: Path) -> Optional[Dict[str, Any]]:
    path = Path(root) / STAMP_FILE
    if not path.exists():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, UnicodeDecodeError, ValueError) as exc:
        raise StampError("%s is not readable JSON: %s" % (STAMP_FILE.as_posix(), exc))
    if not isinstance(data, dict):
        raise StampError("%s must contain a JSON object" % STAMP_FILE.as_posix())
    if "profiles" in data:
        entries = data["profiles"]
        if not isinstance(entries, list) or not all(isinstance(e, dict) and isinstance(e.get("name"), str)
                                                    for e in entries):
            raise StampError("%s: `profiles` must be a list of {name, added, by}" % STAMP_FILE.as_posix())
    return data


def names(root: Path) -> List[str]:
    data = _read(root)
    return [e["name"] for e in (data or {}).get("profiles", [])]


def _write(root: Path, data: Dict[str, Any]) -> None:
    path = Path(root) / STAMP_FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".harness-json-", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
        os.replace(tmp, str(path))
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def add(root: Path, new: Sequence[str], by: str, today: Optional[str] = None,
        profiles_dir: Optional[Path] = None) -> Dict[str, Any]:
    """HJ-01, HJ-03: appends the profiles that are absent."""
    if by not in BY_VALUES:
        raise StampError("by must be one of %s, got %r" % ("|".join(BY_VALUES), by))
    known = profiles.discover(profiles_dir)
    for name in new:
        if name not in known:
            raise StampError("unknown profile: %r (known: %s)" % (name, ", ".join(known)))
    data = _read(root)
    existing = list((data or {}).get("profiles", []))
    present = [e["name"] for e in existing]
    added = [n for n in dict.fromkeys(new) if n not in present]
    if not added:
        return {"added": [], "kept": present, "written": False}
    stamp_date = today or date.today().isoformat()
    data = dict(data or {})
    data["profiles"] = existing + [{"name": n, "added": stamp_date, "by": by} for n in added]
    _write(root, data)
    return {"added": added, "kept": present, "written": True}


def inferred(root: Path) -> List[str]:
    """HJ-04 step 2: profiles whose generated files exist (installation before Phase 2)."""
    root = Path(root)
    found: List[str] = []
    for name, prof in profiles.discover().items():
        orch = prof["orchestrator"]["name"]
        agents = [r["agent_file"] for r in prof["roles"]]
        if (root / ".claude" / "skills" / orch / "SKILL.md").is_file() or any((root / a).is_file() for a in agents):
            found.append(name)
    return found


def resolve(root: Path) -> Dict[str, Any]:
    stamped = names(root)
    if stamped:
        return {"source": "stamp", "profiles": stamped}
    guess = inferred(root)
    if guess:
        return {"source": "inferred", "profiles": guess}
    return {"source": "none", "profiles": []}


def compare(root: Path, verdict: Dict[str, Any]) -> Dict[str, List[str]]:
    """EP-03: added (retained and absent from the stamp), kept, vanished
    (stamped and now rejected)."""
    stamped = resolve(root)["profiles"]
    status = {p["name"]: p["status"] for p in verdict.get("profiles", [])}
    retained = [n for n, s in status.items() if s == "retained"]
    return {"added": [n for n in retained if n not in stamped],
            "kept": [n for n in stamped if n in retained],
            "vanished": [n for n in stamped if status.get(n) == "rejected"]}


# ------------------------------------------------------------- Phase 3

SCHEMA_VERSION = 1
SKILL_NAMES = ("software-factory", "code-index")
_ABSOLUTE = re.compile(r"^(?:[A-Za-z]:[\\/]|/)")


def now_iso(now: Optional[datetime] = None) -> str:
    """HJ-11: local time with offset, to the second."""
    return (now or datetime.now()).astimezone().replace(microsecond=0).isoformat()


def dumps(data: Dict[str, Any]) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def _walk_strings(value: Any, path: str = ""):
    if isinstance(value, dict):
        for key, child in value.items():
            yield from _walk_strings(child, path + "." + str(key))
    elif isinstance(value, list):
        for i, child in enumerate(value):
            yield from _walk_strings(child, "%s[%d]" % (path, i))
    elif isinstance(value, str):
        yield path, value


def _keys(value: Any):
    if isinstance(value, dict):
        for key, child in value.items():
            yield key
            yield from _keys(child)
    elif isinstance(value, list):
        for child in value:
            yield from _keys(child)


def validate_data(data: Any) -> List[str]:
    """HJ-07, HJ-12."""
    if not isinstance(data, dict):
        return ["the stamp must be a JSON object"]
    errors: List[str] = []
    if "schema_version" in data and data["schema_version"] != SCHEMA_VERSION:
        errors.append("unknown schema_version: %r" % (data["schema_version"],))
    for key in set(_keys(data)):
        if key == "rg_path":
            errors.append("key rg_path is machine specific and must not be versioned")
    for where, text in _walk_strings(data):
        if _ABSOLUTE.match(text):
            errors.append("%s: absolute path %r (the stamp is versioned: nothing machine specific)" % (where, text))
    skills = data.get("skills")
    if skills is not None and not isinstance(skills, dict):
        errors.append("`skills` must be an object")
    return errors


def validate_file(path: Path) -> List[str]:
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8-sig"))
    except (OSError, UnicodeDecodeError, ValueError) as exc:
        return ["%s is not readable JSON: %s" % (path, exc)]
    return validate_data(data)


def show(root: Path) -> Dict[str, Any]:
    data = _read(root)
    return {"present": data is not None, "stamp": data}


def set_hooks_lint(root: Path, entries: Sequence[Dict[str, Any]]) -> Dict[str, Any]:
    """HL-01: `hooks.lint` of the stamp: [{glob, argv (with {file}), timeout_s}], verification commands only."""
    clean = []
    for e in entries:
        argv = e.get("argv") if isinstance(e, dict) else None
        if not (isinstance(e, dict) and isinstance(e.get("glob"), str) and e["glob"].strip() and isinstance(argv, list)
                and argv and all(isinstance(a, str) for a in argv) and any("{file}" in a for a in argv)):
            raise StampError("hooks.lint entries are {glob, argv (with {file}), timeout_s}, got %r" % (e,))
        clean.append({"glob": e["glob"], "argv": list(argv), "timeout_s": int(e.get("timeout_s", 30))})
    data = dict(_read(root) or {})
    hooks = dict(data.get("hooks") or {})
    if hooks.get("lint") == clean:
        return {"lint": clean, "written": False}
    hooks["lint"] = clean
    data["hooks"] = hooks
    _write(root, data)
    return {"lint": clean, "written": True}


def ensure_autonomy(root: Path, value: Optional[str] = None) -> Dict[str, Any]:
    """AP-05: writes `autonomy` (default `auto`, or the --autonomy value) when the key is absent.
    An existing value is never replaced and the file is then left untouched."""
    wanted = value or "auto"
    if wanted not in ("gate", "auto"):
        raise StampError("autonomy must be gate or auto, got %r" % (wanted,))
    data = _read(root)
    if data is not None and "autonomy" in data:
        return {"value": data["autonomy"], "written": False}
    data = dict(data or {})
    data["autonomy"] = wanted
    _write(root, data)
    return {"value": wanted, "written": True}


def compose(existing: Optional[Dict[str, Any]], skill: str, entry: Dict[str, Any],
            profile_names: Sequence[str] = (), by: str = "inferred", today: Optional[str] = None,
            migrations: Sequence[Dict[str, Any]] = (), inferred_from: Optional[str] = None) -> Dict[str, Any]:
    """HJ-07 to HJ-10, HJ-13: the stamp after an upgrade or an installation (pure)."""
    data: Dict[str, Any] = json.loads(json.dumps(existing)) if existing else {}
    data.setdefault("schema_version", SCHEMA_VERSION)
    data.setdefault("autonomy", "auto")
    present = [e["name"] for e in data.setdefault("profiles", [])]
    stamp_date = today or date.today().isoformat()
    for name in profile_names:
        if name not in present:
            data["profiles"].append({"name": name, "added": stamp_date, "by": by})
            present.append(name)
    skills = data.setdefault("skills", {})
    skills[skill] = entry
    if migrations:
        data["migrations"] = list(data.get("migrations", [])) + [dict(m) for m in migrations]
    if inferred_from and "inferred_from" not in data and not existing:
        data["inferred_from"] = inferred_from
    return data


def markers_of_code_index(root: Path) -> bool:
    root = Path(root)
    if (root / ".claude" / "rgkb" / "rgkb.py").is_file() or (root / ".knowledge" / "manifest.json").is_file():
        return True
    try:
        mcp = json.loads((root / ".mcp.json").read_text(encoding="utf-8-sig"))
        return isinstance(mcp.get("mcpServers"), dict) and "rgkb" in mcp["mcpServers"]
    except (OSError, UnicodeDecodeError, ValueError, AttributeError):
        return False


def inferred_skills(root: Path) -> List[str]:
    """DT-01."""
    found = []
    if inferred(root):
        found.append("software-factory")
    if markers_of_code_index(root):
        found.append("code-index")
    return found


def resolve_full(root: Path) -> Dict[str, Any]:
    """HJ-04 extended by DT-01 and DT-02: profiles, skills and estimated generation."""
    from . import history  # local: history reads the core tree, stamp is imported by everything
    base = resolve(root)
    data = _read(root) or {}
    stamped = [s for s in SKILL_NAMES if s in (data.get("skills") or {})]
    found = inferred_skills(root)
    base["skills"] = [s for s in SKILL_NAMES if s in stamped or s in found]
    if base["source"] == "none" and not base["skills"]:
        base["generation"] = None
    elif base["source"] == "none":
        base["generation"] = "pre-core" if not (Path(root) / ".claude" / "harness").is_dir() else "core-unknown"
    elif base["source"] == "stamp":
        base["generation"] = "stamp" if data.get("schema_version") else "stamp-phase2"
    else:
        dest = Path(root) / ".claude" / "harness"
        if not dest.is_dir():
            base["generation"] = "pre-core"
        else:
            info = history.installed_core(dest, history.load(history.CORE_DIR))
            base["generation"] = ("core-%s" % info["core_version"]) if info.get("core_version") else "core-unknown"
            if info.get("mixed"):
                base["generation"] = "core-mixed"
    return base
